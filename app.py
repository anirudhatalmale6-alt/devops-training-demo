"""
Simple Calculator App - DevOps Training Demo
This app demonstrates basic Python functions with unit tests
for CI/CD pipeline demonstration.
"""

def add(a, b):
    return a + b

def subtract(a, b):
    return a - b

def multiply(a, b):
    return a * b

def divide(a, b):
    if b == 0:
        raise ValueError("Cannot divide by zero")
    return a / b

def main():
    print("=== Simple Calculator ===")
    print(f"5 + 3 = {add(5, 3)}")
    print(f"10 - 4 = {subtract(10, 4)}")
    print(f"6 * 7 = {multiply(6, 7)}")
    print(f"15 / 3 = {divide(15, 3)}")
    print("=========================")

if __name__ == "__main__":
    main()
